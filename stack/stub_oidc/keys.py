"""The stub issuer's one RSA key, and RS256, with the standard library and nothing else.

**Why this file exists at all.** keel-cloud verifies an ID token against a JWKS (keel-cloud
`canon/designs/google-sign-in-design.md` §3.3, G3) -- so the stub has to *sign* one, RS256, for
real. RSA is the one thing `hashlib`/`hmac` cannot do, and this harness has no `cryptography`:
`requirements.txt` is pytest, playwright, requests, pyyaml, and playwright's own venv brings none
either (checked, 2026-09-09). The design (§10.1) allows either a vendored test key or the
`cryptography` package; this repository has neither, so:

**The decision, stated once.** The *key* is generated by `openssl genrsa` at `make up`
(`stack/oidc.py:ensure_key`) into `runs/.stack/`, and the *arithmetic* is done here in pure
Python -- `pow(m, d, n)` is a built-in, and PKCS#1 v1.5 over a SHA-256 DigestInfo is nineteen
constant bytes and a run of `0xff`. That buys three things a vendored key would not: nothing
secret-shaped is ever committed, the key is fresh every `make up` and dies with the run, and
signing costs no subprocess per token (one `openssl` call per boot, none per login).

`openssl` is a system tool, not a dependency of this harness; when it is missing the error says so
and names the one command that fixes it. Nothing here is a general-purpose crypto library and
nothing outside this stub may use it: it signs tokens that are worth nothing, for an issuer
reachable only because `KEEL_OIDC_ISSUER` names it (§10.8).
"""

from __future__ import annotations

import base64
import hashlib
import json
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

KID = "stub-1"
ALG = "RS256"

# RFC 8017 §9.2, the DigestInfo prefix for SHA-256. Nineteen bytes, and they never change.
_SHA256_DIGEST_INFO = bytes([
    0x30, 0x31, 0x30, 0x0D, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01,
    0x65, 0x03, 0x04, 0x02, 0x01, 0x05, 0x00, 0x04, 0x20,
])


class KeyError_(RuntimeError):
    """A key this stub cannot generate, read, or make sense of."""


def b64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def b64url_decode(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def _int_to_bytes(value: int) -> bytes:
    return value.to_bytes((value.bit_length() + 7) // 8 or 1, "big")


# ----------------------------------------------------------------------------- DER, minimally

def _read_tlv(buf: bytes, index: int) -> tuple[int, bytes, int]:
    """One DER tag-length-value at `index`; returns (tag, content, index after it)."""
    if index + 2 > len(buf):
        raise KeyError_("truncated DER while reading a private key")
    tag = buf[index]
    first = buf[index + 1]
    index += 2
    if first < 0x80:
        length = first
    else:
        count = first & 0x7F
        length = int.from_bytes(buf[index:index + count], "big")
        index += count
    content = buf[index:index + length]
    if len(content) != length:
        raise KeyError_("truncated DER while reading a private key")
    return tag, content, index + length


def _read_integers(sequence: bytes, how_many: int) -> list[int]:
    values: list[int] = []
    index = 0
    while index < len(sequence) and len(values) < how_many:
        tag, content, index = _read_tlv(sequence, index)
        if tag != 0x02:
            raise KeyError_(f"expected a DER INTEGER, got tag 0x{tag:02x}")
        values.append(int.from_bytes(content, "big"))
    if len(values) != how_many:
        raise KeyError_(f"expected {how_many} DER INTEGERs, found {len(values)}")
    return values


@dataclass(frozen=True)
class RsaKey:
    """An RSA key pair as three integers -- modulus, public exponent, private exponent. The CRT
    parameters are parsed and dropped: `pow(m, d, n)` is fast enough that halving it would be the
    only reason to keep them, and this signs at most a few tokens a run."""

    n: int
    e: int
    d: int

    @property
    def size_bytes(self) -> int:
        return (self.n.bit_length() + 7) // 8

    def sign(self, message: bytes) -> bytes:
        """RSASSA-PKCS1-v1_5 over SHA-256 (RFC 8017 §8.2.1) -- the `RS256` of RFC 7518."""
        digest_info = _SHA256_DIGEST_INFO + hashlib.sha256(message).digest()
        padding_len = self.size_bytes - len(digest_info) - 3
        if padding_len < 8:
            raise KeyError_("RSA modulus is too small to sign a SHA-256 digest")
        block = b"\x00\x01" + b"\xff" * padding_len + b"\x00" + digest_info
        signature = pow(int.from_bytes(block, "big"), self.d, self.n)
        return signature.to_bytes(self.size_bytes, "big")

    def public_jwk(self) -> dict:
        """The one key `/jwks` serves (§10.1): `kty: RSA`, `alg: RS256`, `use: sig`,
        `kid: stub-1`."""
        return {
            "kty": "RSA",
            "use": "sig",
            "alg": ALG,
            "kid": KID,
            "n": b64url(_int_to_bytes(self.n)),
            "e": b64url(_int_to_bytes(self.e)),
        }


def parse_pem_private_key(pem: str) -> RsaKey:
    """Reads either PEM an `openssl genrsa` might hand us: PKCS#8 (`BEGIN PRIVATE KEY`, what
    OpenSSL 3.x writes by default) or PKCS#1 (`BEGIN RSA PRIVATE KEY`, what 1.x wrote and what
    `-traditional` still writes). Both end in the same nine-INTEGER sequence."""
    body = []
    inside = False
    for line in pem.splitlines():
        if line.startswith("-----BEGIN"):
            inside = True
            continue
        if line.startswith("-----END"):
            break
        if inside:
            body.append(line.strip())
    if not body:
        raise KeyError_("no PEM block found in the stub issuer's key file")
    der = base64.b64decode("".join(body))

    tag, outer, _ = _read_tlv(der, 0)
    if tag != 0x30:
        raise KeyError_("a private key PEM must hold a DER SEQUENCE")

    # PKCS#1: SEQUENCE { version, n, e, d, p, q, dp, dq, qinv }.
    # PKCS#8: SEQUENCE { version, AlgorithmIdentifier, OCTET STRING { the PKCS#1 above } }.
    first_tag, _, after_first = _read_tlv(outer, 0)
    second_tag, _, after_second = _read_tlv(outer, after_first)
    if first_tag == 0x02 and second_tag == 0x30:
        third_tag, inner, _ = _read_tlv(outer, after_second)
        if third_tag != 0x04:
            raise KeyError_("PKCS#8 private key without an OCTET STRING payload")
        inner_tag, outer, _ = _read_tlv(inner, 0)
        if inner_tag != 0x30:
            raise KeyError_("PKCS#8 payload is not an RSAPrivateKey SEQUENCE")

    version, n, e, d = _read_integers(outer, 4)
    if version != 0:
        raise KeyError_(f"unsupported RSAPrivateKey version {version} (multi-prime?)")
    return RsaKey(n=n, e=e, d=d)


def generate_pem(path: Path, *, bits: int = 2048) -> Path:
    """`openssl genrsa` into `path`, 0600. Called once per `make up`, never per request."""
    openssl = shutil.which("openssl")
    if openssl is None:
        raise KeyError_(
            "the stub OIDC issuer needs `openssl` on PATH to generate its signing key "
            "(this harness has no `cryptography` package -- see stack/stub_oidc/keys.py). "
            "Install it (macOS: it ships with the system; Debian: `apt-get install openssl`) "
            "and re-run `make up`."
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [openssl, "genrsa", "-out", str(path), str(bits)],
        capture_output=True, text=True, timeout=60,
    )
    if result.returncode != 0 or not path.exists():
        raise KeyError_(f"`openssl genrsa` failed: {result.stderr.strip() or result.returncode}")
    path.chmod(0o600)
    return path


def load_or_generate(path: Path, *, bits: int = 2048) -> RsaKey:
    if not path.exists():
        generate_pem(path, bits=bits)
    return parse_pem_private_key(path.read_text())


# --------------------------------------------------------------------------------------- JWT

def sign_jwt(key: RsaKey, claims: dict, *, kid: str = KID) -> str:
    """A compact RS256 JWS. The header carries `kid` because keel-cloud selects the JWKS key by
    it (§3.3) -- a stub that omitted it would let a bug in that selection pass."""
    header = {"alg": ALG, "typ": "JWT", "kid": kid}
    segments = [
        b64url(json.dumps(header, separators=(",", ":"), sort_keys=True).encode()),
        b64url(json.dumps(claims, separators=(",", ":"), sort_keys=True).encode()),
    ]
    signing_input = ".".join(segments).encode("ascii")
    segments.append(b64url(key.sign(signing_input)))
    return ".".join(segments)


def verify_rs256(token: str, jwk: dict) -> dict:
    """Verifies a compact RS256 JWS against a public JWK and returns its claims.

    This is here so `tests/test_stub_oidc.py` can prove the token the stub issues actually
    verifies against the JWKS it publishes -- the one property keel-cloud's whole verifier
    depends on. It is a *test-side* verifier: it checks the signature and nothing about the
    claims, which are the caller's to assert.
    """
    try:
        header_b64, claims_b64, signature_b64 = token.split(".")
    except ValueError:
        raise KeyError_("not a compact JWS: expected three dot-separated segments") from None
    header = json.loads(b64url_decode(header_b64))
    if header.get("alg") != ALG:
        raise KeyError_(f"expected alg {ALG}, got {header.get('alg')!r}")
    if jwk.get("kid") and header.get("kid") != jwk["kid"]:
        raise KeyError_(f"kid {header.get('kid')!r} is not this key's {jwk['kid']!r}")

    n = int.from_bytes(b64url_decode(jwk["n"]), "big")
    e = int.from_bytes(b64url_decode(jwk["e"]), "big")
    size = (n.bit_length() + 7) // 8
    signature = b64url_decode(signature_b64)
    if len(signature) != size:
        raise KeyError_("signature length does not match the modulus")

    recovered = pow(int.from_bytes(signature, "big"), e, n).to_bytes(size, "big")
    digest_info = _SHA256_DIGEST_INFO + hashlib.sha256(
        f"{header_b64}.{claims_b64}".encode("ascii")).digest()
    expected = b"\x00\x01" + b"\xff" * (size - len(digest_info) - 3) + b"\x00" + digest_info
    if recovered != expected:
        raise KeyError_("RS256 signature does not verify against this key")
    return json.loads(b64url_decode(claims_b64))
